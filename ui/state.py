"""Session state and the shared sidebar (data inputs, date range, rule settings).

streamlit_app.py calls setup() on every run, before the selected page runs.
Pages call require_data() to get a Context, or stop with a helpful message.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

import duckdb
import streamlit as st

from retailpulse import db, metrics
from retailpulse.config import DEFAULT_THRESHOLDS, Thresholds
from retailpulse.report import DatasetReport
from retailpulse.schema import DATE_FORMATS
from retailpulse.validate import validate_dataset
from ui import format as fmt

# Fictional demo shop generated by scripts/generate_sample_data.py (see data/sample/README.md).
SAMPLE_DIR = Path(__file__).parents[1] / "data" / "sample"
DATA_PAGE = "app_pages/data_quality.py"
PRESETS = {"All data": None, "Last 7 days": 7, "Last 30 days": 30, "Last 90 days": 90,
           "Custom range": "custom"}


@dataclass(frozen=True)
class Context:
    """Everything a page needs to render analytics."""

    con: duckdb.DuckDBPyConnection
    report: DatasetReport
    source: str
    start: date
    end: date
    data_start: date
    as_of: date
    thresholds: Thresholds


def connection() -> duckdb.DuckDBPyConnection:
    if "con" not in st.session_state:
        st.session_state.con = db.connect()
    return st.session_state.con


def _inputs() -> tuple[bytes | None, bytes | None, str]:
    st.sidebar.header("Your data")
    sales_file = st.sidebar.file_uploader("Sales CSV (required)", type=["csv"])
    products_file = st.sidebar.file_uploader(
        "Products CSV (optional)", type=["csv"],
        help="Add unit_cost to unlock profit, and on_hand_qty to unlock inventory health.")
    if st.sidebar.button("Use sample data", key="sample_button", width="stretch"):
        st.session_state.use_sample = True
    if sales_file is not None:
        st.session_state.use_sample = False

    if st.session_state.get("use_sample"):
        return ((SAMPLE_DIR / "sales.csv").read_bytes(),
                (SAMPLE_DIR / "products.csv").read_bytes(), "Sample data (fictional coffee shop)")
    if sales_file is None:
        return None, None, ""
    return sales_file.getvalue(), products_file.getvalue() if products_file else None, (
        sales_file.name)


def _validate(con, sales: bytes, products: bytes | None) -> tuple[DatasetReport, str]:
    """Validate (and build the marts) only when the files or the date format change."""
    date_format = st.session_state.get("date_format")
    key = hashlib.sha256(sales + b"|" + (products or b"") + str(date_format).encode()).hexdigest()
    if st.session_state.get("report_key") != key:
        report = validate_dataset(con, sales, products, date_format=date_format)
        if report.ok:
            metrics.build(con)
        st.session_state.report = report
        st.session_state.report_key = key
    return st.session_state.report, key


def _date_format_picker(report: DatasetReport) -> None:
    if not (report.sales.date_format_candidates and report.sales.find("ambiguous_date_format")):
        return
    choice = st.sidebar.selectbox(
        "Your dates could be read more than one way. Which format does your file use?",
        report.sales.date_format_candidates, format_func=DATE_FORMATS.get, index=None)
    if choice:
        st.session_state.date_format = choice
        st.rerun()


def _date_filter(key: str, data_start: date, as_of: date) -> tuple[date, date]:
    st.sidebar.header("Filters")
    preset = st.sidebar.selectbox("Date range", list(PRESETS), key=f"preset:{key}",
                                  help="Presets count back from the last date in your data.")
    days = PRESETS[preset]
    if days is None:
        start, end = data_start, as_of
    elif days == "custom":
        picked = st.sidebar.date_input("From – to", value=(data_start, as_of),
                                       min_value=data_start, max_value=as_of,
                                       key=f"custom:{key}")
        start, end = (picked[0], picked[-1]) if len(picked) == 2 else (picked[0], as_of)
    else:
        start, end = max(data_start, as_of - timedelta(days=days - 1)), as_of
    st.sidebar.caption(fmt.date_range(start, end))
    return start, end


def _rule_settings() -> Thresholds:
    d = DEFAULT_THRESHOLDS
    with st.sidebar.expander("Rule settings"):
        st.caption("Thresholds for inventory status and recommendations.")
        low_cover = st.number_input("Low cover: under N days of stock", 1, 365, d.low_cover_days)
        slow = st.number_input("Slow-moving: over N days of stock", 1, 3650,
                               d.slow_moving_cover_days)
        dead = st.number_input("Dead stock: no sales in N days", 1, 3650, d.dead_stock_days)
        window = st.number_input("Sales rate window (days)", 1, 365, d.velocity_window_days)
        margin = st.number_input("Low margin: under N %", 0, 100, int(d.low_margin_pct * 100))
        clearance = st.number_input("Clearance: dead stock worth at least", 0, 10_000_000,
                                    int(d.clearance_min_stock_value), step=50)
    return Thresholds(
        velocity_window_days=window, dead_stock_days=dead, slow_moving_cover_days=slow,
        low_cover_days=low_cover, low_margin_pct=Decimal(margin) / 100,
        clearance_min_stock_value=Decimal(clearance), abc_a_cutoff=d.abc_a_cutoff,
        abc_b_cutoff=d.abc_b_cutoff, data_gap_min_cost_coverage=d.data_gap_min_cost_coverage,
    )


def setup() -> None:
    """Render the sidebar and store the Context (or None) for the page about to run."""
    con = connection()
    st.session_state.ctx = None
    sales, products, source = _inputs()
    if sales is None:
        st.session_state.pop("report", None)
        st.session_state.pop("report_key", None)
        return
    report, key = _validate(con, sales, products)
    _date_format_picker(report)
    if not report.ok:
        return
    data_start, as_of = metrics.date_bounds(con)
    start, end = _date_filter(key, data_start, as_of)
    st.session_state.ctx = Context(con, report, source, start, end, data_start, as_of,
                                   _rule_settings())


def require_data() -> Context:
    """The current Context, or show why there isn't one and stop the page."""
    ctx = st.session_state.get("ctx")
    if ctx is not None:
        return ctx
    report = st.session_state.get("report")
    if report is None:
        st.info("Upload a sales CSV in the sidebar, or click **Use sample data** to explore.",
                icon=":material/upload_file:")
        st.markdown("Required columns: `order_date, order_id, sku, quantity, unit_price`. "
                    "Optional: `discount_amount, product_name, category`. Add a products file "
                    "with `unit_cost` and `on_hand_qty` to unlock profit and inventory.")
    else:
        st.error("This data can't be analysed yet. See what needs fixing on the Data quality "
                 "page.", icon=":material/error:")
        st.page_link(DATA_PAGE, label="Open Data quality", icon=":material/fact_check:")
    st.stop()
